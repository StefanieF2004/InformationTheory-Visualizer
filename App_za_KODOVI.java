    /**
      HELPER CLASS: Symbol
      Represents the input symbols of the information source
      (e.g., alpha_1, alpha_2, etc.).
      For each symbol, its name, probability, and final code
      generated by the algorithm are stored.
     */
    static class Symbol {
        String name;          // Symbol name (example: "a1")
        double probability;   // Probability of occurrence (p_i)
        String code = "";     // Final binary code (example: "010")

        public Symbol(String name, double probability) {
            this.name = name;
            this.probability = probability;
        }
    }

    /**
      HELPER CLASS: Node
      Represents a node in the coding tree (used for Huffman and Shannon-Fano).
      This class stores the coordinates (x, y) used for drawing.
     */
    static class Node {
        double prob;                // Total probability of this node (or subtree sum)
        String text = "";           // Text displayed inside the bubble/box
        List<Node> children = new ArrayList<>(); // Child nodes (tree branches)
        int x, y;                   // Screen coordinates where the node will be drawn
        boolean isLeaf;             // Indicates whether the node is a leaf (final symbol) or an internal node

        public Node(String text, double prob, boolean isLeaf) {
            this.text = text;
            this.prob = prob;
            this.isLeaf = isLeaf;
        }

        /**
          Used to save the current state of the tree at a specific step,
          preventing subsequent changes from affecting the visualization
          of that step.
         */
        public Node makeCopy() {
            Node copy = new Node(this.text, this.prob, this.isLeaf);
            copy.x = this.x;
            copy.y = this.y;
            for (Node child : this.children) {
                copy.children.add(child.makeCopy()); // Recursively copy the children
            }
            return copy;
        }
    }

    /**
      HELPER CLASS: VisualLine
      Used exclusively by the graphics panel. Stores the starting and ending
      coordinates of the lines connecting the tree nodes, as well as the
      label (0 or 1) displayed above each line.
     */
    static class VisualLine {
        int x1, y1, x2, y2; // Line coordinates
        String label;       // Branch label (usually "0" for left and "1" for right)

        public VisualLine(int x1, int y1, int x2, int y2, String label) {
            this.x1 = x1;
            this.y1 = y1;
            this.x2 = x2;
            this.y2 = y2;
            this.label = label;
        }
    }

